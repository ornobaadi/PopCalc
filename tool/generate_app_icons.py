"""Builds the alternate launcher icons from assets/brand_assets/icons/<id>/.

Each source folder holds 1024 px foreground.png (art in the central 66%), monochrome.png
(white silhouette) and full.png (finished square, reference only). This writes the Android adaptive-icon
layers for every density, legacy PNGs for pre-API-26 launchers, the background colours,
and the small previews the app shows in Settings and on the splash.

Run from the repo root: python tool/generate_app_icons.py
The official icon (ic_launcher) is never touched.
"""
import os
from PIL import Image, ImageDraw

SRC = 'assets/brand_assets/icons'
RES = 'android/app/src/main/res'
PREVIEWS = 'assets/app_icons'

# id -> adaptive background colour. Order matches kAppIcons in lib/core/app_icon/app_icons.dart.
ICONS = {
    'amber': '#FFAB00',
    'percent': '#141414',
    'plusminus': '#F4F1EA',
    'operators': '#141414',
    'keypad': '#141414',
    'root': '#FFAB00',
    'ruler': '#141414',
}
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
PREVIEW_SIZE = 256
# Longest side of the art as a share of the 108 dp canvas. Launchers show only the
# middle 72 dp (2/3), so art filling the supplied 66 % ran edge to edge on the home
# screen. The official ic_launcher art is about 0.50; match it.
ART = 0.45
VISIBLE = 72 / 108


def rounded(img, radius_ratio=0.22):
    mask = Image.new('L', img.size, 0)
    r = int(img.size[0] * radius_ratio)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, img.size[0] - 1, img.size[1] - 1), r, fill=255)
    out = img.convert('RGBA')
    out.putalpha(mask)
    return out


def fit(layer, bbox):
    """Centres the art and scales its longest side to ART of the canvas."""
    n = layer.size[0]
    x0, y0, x1, y1 = bbox
    art = layer.crop(bbox)
    k = ART * n / max(x1 - x0, y1 - y0)
    art = art.resize((max(1, round(art.width * k)), max(1, round(art.height * k))), Image.LANCZOS)
    out = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    out.paste(art, ((n - art.width) // 2, (n - art.height) // 2), art)
    return out


def as_launched(fg, colour):
    """What a launcher draws: background + foreground, cropped to the visible 2/3."""
    n = fg.size[0]
    img = Image.new('RGBA', (n, n), colour)
    img.alpha_composite(fg)
    m = round(n * (1 - VISIBLE) / 2)
    return img.crop((m, m, n - m, n - m))


def art_bbox(*layers):
    boxes = [l.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox() for l in layers]
    return (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))


def save(img, path, size):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.resize((size, size), Image.LANCZOS).save(path, optimize=True)


def main():
    colours = []
    for icon_id, colour in ICONS.items():
        src = os.path.join(SRC, icon_id)
        fg = Image.open(os.path.join(src, 'foreground.png')).convert('RGBA')
        mono = Image.open(os.path.join(src, 'monochrome.png')).convert('RGBA')
        box = art_bbox(fg, mono)  # one transform for both, so themed icons line up
        fg, mono = fit(fg, box), fit(mono, box)
        face = as_launched(fg, colour)
        name = f'ic_launcher_{icon_id}'
        for d, k in DENSITIES.items():
            save(fg, f'{RES}/mipmap-{d}/{name}_foreground.png', int(108 * k))
            save(mono, f'{RES}/mipmap-{d}/{name}_monochrome.png', int(108 * k))
            save(rounded(face), f'{RES}/mipmap-{d}/{name}.png', int(48 * k))
        os.makedirs(f'{RES}/mipmap-anydpi-v26', exist_ok=True)
        with open(f'{RES}/mipmap-anydpi-v26/{name}.xml', 'w', newline='\n') as f:
            f.write(
                '<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                f'    <background android:drawable="@color/{name}_background"/>\n'
                f'    <foreground android:drawable="@mipmap/{name}_foreground"/>\n'
                f'    <monochrome android:drawable="@mipmap/{name}_monochrome"/>\n'
                '</adaptive-icon>\n')
        colours.append(f'    <color name="{name}_background">{colour}</color>\n')
        save(face, f'{PREVIEWS}/{icon_id}.png', PREVIEW_SIZE)
    with open(f'{RES}/values/ic_launcher_alt_colors.xml', 'w', newline='\n') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/generate_app_icons.py -->\n<resources>\n'
                + ''.join(colours) + '</resources>\n')
    # The official icon as a Settings preview, so the default tile looks like the others.
    official = Image.open(f'{RES}/mipmap-xxxhdpi/ic_launcher_foreground.png').convert('RGBA')
    save(as_launched(official, '#FFAE00'), f'{PREVIEWS}/classic.png', PREVIEW_SIZE)
    print('app icons written:', ', '.join(ICONS))


if __name__ == '__main__':
    main()
